    p=&init_code[0];
	memset(dest,0x00,sizeof(dest));

	SPI_Write(0xFE,0x20);
  	SPI_Write(0xF4,0x5A);
  	SPI_Write(0xF5,0x59);

	printf("read star\r\n"); 
  	_DEBUG("read star\r\n");  
    for(i=0;i<(sizeof(init_code)/sizeof(init_code[0]));i++,p++)
    {
		if(p->data[0]==0xFE)//Switch page
		{	
//			SDCard_Printf(LOG_filename,dest);  //把缓存的数据保存在SD卡
//			memset(dest,0x00,sizeof(dest));    //清空缓存

			SPI_Write(p->data[0],p->data[1]);	
			printf("0x%02X,0x%02X:\r\n",p->data[0],p->data[1]);
//			_DEBUG("Page 0x%02x\r\n",p->data[1]);
//			sprintf(src,"  W:0x%02x;0x%02x;",p->data[0],p->data[1]);  
//			SDCard_Printf(LOG_filename,src);//保存LOG
		}else
		{
			
			SPI_Read_Buffer(p->data[0],(uint16_t *)RD_code, (p->package_long)-1);
			// printf("0x%02x,",p->data[0]);
			for(j=0;j<p->package_long-1;j++)
			{
				if(p->data[j+1] == RD_code[j])   //compare read data and save
				{
						// printf("0x%02x,",RD_code[j]);

//						sprintf(src,"0x%02x;",p->data[j]);
//						strcat(dest, src); //放入缓存

				}else	//Read code error
				{
					printf("0x%02x->0x%02x Fail,",p->data[0],RD_code[j]);
//						printf("0x%02x->0x%02x Fail,",p->data[1],RD_code[j]);
//						sprintf(src,"0x%02x->0x%02x;",p->data[1],RD_code[j]);
//						strcat(dest, src); //放入缓存

					result = -1;
					break;
				}					
			}
			// printf("\r\n");

		}
		if( i/20 )
		{
//			SDCard_Printf(LOG_filename,dest);  //把缓存的数据保存在SD卡
			memset(dest,0x00,sizeof(dest));    //清空缓存
		}
    }
//	SDCard_Printf(LOG_filename,",");
//	_DEBUG("read end: %d \r\n",result);
